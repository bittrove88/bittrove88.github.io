"""Compile approved component materials and the shared vector renderer for gameplay."""
import hashlib,json
from release import ROOT

def build():
    art=ROOT/'design/components/complete'
    approval=json.loads((ROOT/'design/components/runtime-approval.json').read_text())
    for reference in approval['materials']:
        source=ROOT/reference['file']
        assert hashlib.sha256(source.read_bytes()).hexdigest()==reference['sha256'],'Unreviewed material: '+reference['file']
    scenes={}
    for source in sorted((art/'data').glob('*.json')):
        row=json.loads(source.read_text())
        scenes[row['id']]={key:row[key] for key in ['id','title','kind','themeIndex','stage','mapIndex','materials']}
    assert len(scenes)==33
    assert len([s for s in scenes.values() if s['kind']=='normal'])==20
    assert len([s for s in scenes.values() if s['kind']=='boss'])==9
    assert len([s for s in scenes.values() if s['kind']=='final'])==4
    backgrounds=json.loads((ROOT/'design/backgrounds/complete/manifest.json').read_text())
    assert set(scenes)=={s['id'] for s in backgrounds['scenes']}
    data={'scenes':scenes,'shared':json.loads((art/'shared-materials.json').read_text())['materials'],'renderStyle':json.loads((art/'render-style.json').read_text()),'approval':approval}
    bundle='/* Generated by game/tools/build_components.py. Edit approved materials, the vector renderer or game/ui/component-art.js. */\n'
    bundle+=(art/'renderer.js').read_text()+'\n'
    bundle+='(function(root){root.ArcComponentMaterials='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';})(globalThis);\n'
    bundle+=(ROOT/'game/ui/component-art.js').read_text()
    (ROOT/'game/dist/component-art.js').write_text(bundle)

if __name__=='__main__':build()
