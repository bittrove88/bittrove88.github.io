"""Bundle the reviewed vector artwork and its runtime adapter without network loads."""
import json
from release import ROOT


def build():
    art = ROOT / 'design/backgrounds/complete'
    manifest = json.loads((art / 'manifest.json').read_text())
    scenes = [json.loads((art / row['json']).read_text()) for row in manifest['scenes']]
    assert len(scenes) == 33 and len({s['id'] for s in scenes}) == 33
    bundle = '/* Generated by game/tools/build_backgrounds.py. Edit the artwork or game/ui/backgrounds.js. */\n'
    bundle += (art / 'renderer.js').read_text() + '\n'
    bundle += '(function(root){root.ArcBackgroundScenes='
    bundle += json.dumps(scenes, ensure_ascii=False, separators=(',', ':')) + ';})(globalThis);\n'
    bundle += (ROOT / 'game/ui/backgrounds.js').read_text()
    (ROOT / 'game/dist/backgrounds.js').write_text(bundle)


if __name__ == '__main__':
    build()
