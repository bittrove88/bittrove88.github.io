"""Compile drawing identities only. This registry never selects combat AI."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'visual/registry.json').read_text())
assert len(data['actors']) == 42 and len(data['stages']) == 100
assert len({a['id'] for a in data['actors']}) == 42
assert [s['id'] for s in data['stages']] == list(range(1, 101))
assert sum(s['kind'] == 'boss' for s in data['stages']) == 10
assert all(s['kind'] in ['normal', 'midboss', 'boss'] for s in data['stages'])
assert sum(s['kind'] == 'midboss' for s in data['stages']) == 10
ids = {a['id'] for a in data['actors']}
assert all(s['actorId'] in ids and (not s['plannedMidboss'] or s['plannedMidboss'] in ids) for s in data['stages'])
payload = json.dumps(data, ensure_ascii=False, separators=(',', ':'))
code = """(function(root){
'use strict';
// Generated by tools/build_visual_registry.py from visual/registry.json.
// Drawing identity and planned candidates never alter encounter or AI rules.
const data=PAYLOAD;
const freeze=o=>{Object.freeze(o);for(const v of Object.values(o))if(v&&typeof v==='object'&&!Object.isFrozen(v))freeze(v);return o;};
freeze(data);
const byId=new Map(data.actors.map(a=>[a.id,a]));
const fallbacks=freeze(Object.fromEntries(['player','enemy','midboss','boss'].map(kind=>[kind,{id:'legacy:'+kind,kind,key:'legacy',nameJa:'既存の描画',source:null,artStatus:'fallback'}])));
function get(id){return byId.get(id)||null;}
function resolve(id,kind='enemy'){const a=get(id);return a&&a.kind===kind?a:fallbacks[kind]||fallbacks.enemy;}
function stage(id){return Number.isInteger(id)&&id>=1&&id<=100?data.stages[id-1]:null;}
const api=Object.freeze({version:data.version,actors:data.actors,stages:data.stages,namespaces:data.namespaces,get,resolve,stage});
if(typeof module!=='undefined')module.exports=api;else root.ArcVisualRegistry=api;
})(globalThis);
""".replace('PAYLOAD', payload)
(ROOT / 'dist/visual-registry.js').write_text(code)
print('Visual registry: 42 identities / 100 stage mappings / immutable data')
