"""Reproduce alpha-only player/concept cutouts and the shared ending data.

The approved RGB images are immutable. Masks are explicit, reviewed source-space
polygons for players and the existing paper/component masks for concept art.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw
from build_roll_cutouts import mask_crop

ROOT = Path(__file__).resolve().parents[2]

def read(name):
    return json.loads((ROOT / name).read_text())

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

def write(name, data):
    (ROOT / name).write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n')

def build():
    definition = read('design/ending_roll.json')
    inventory = read('design/ending-roll-preparation/player-originals.json')['rows']
    masks = {r['id']: r for r in read('design/ending-roll-preparation/player-masks.json')['rows']}
    actors = []
    for source in inventory:
        path = ROOT / source['src']
        assert sha(path) == source['sha256'], path
        raw = Image.open(path).convert('RGB')
        spec = masks[source['id']]
        # Reviewed alpha mask is a source asset, reproducible by prepare_player_masks.py.
        alpha_path = ROOT / spec['alphaSource']
        assert sha(alpha_path) == spec['alphaSha256'], alpha_path
        alpha = Image.open(alpha_path).convert('L')
        bounds = alpha.getbbox()
        box = (max(0, bounds[0]-2), max(0, bounds[1]-2), min(raw.width, bounds[2]+2), min(raw.height, bounds[3]+2))
        image = raw.crop(box).convert('RGBA')
        image.putalpha(alpha.crop(box))
        output = f"assets/ending/roll-cutouts/players/{source['id']}.png"
        dest = ROOT / output
        dest.parent.mkdir(parents=True, exist_ok=True)
        image.save(dest)
        assert image.convert('RGB').tobytes() == raw.crop(box).tobytes()
        actors.append(dict(id='player:'+source['id'], name=source['name'], src=output,
                           source=source['src'], sourceSha256=source['sha256'], crop=list(box),
                           mask=spec, width=image.width, height=image.height, sha256=sha(dest),
                           anchor={'x': image.width/2, 'y': image.height-4}, rgbPixelsUnchanged=True))
    write('assets/ending/player-cutouts.json', {'method':'Original RGB crop plus alpha-only mask; originals unchanged', 'actors':actors})
    for row in read('design/ending-roll-preparation/cutouts.json')['rows']:
        path = ROOT / row['source']
        assert sha(path) == row['sourceSha256']
        box = row['candidateCrop']
        raw = Image.open(path).convert('RGB').crop(box)
        work = raw.copy()
        draw = ImageDraw.Draw(work)
        for x1,y1,x2,y2 in row['alphaOnlyExclusions']:
            draw.rectangle((max(0,x1-box[0]),max(0,y1-box[1]),min(raw.width-1,x2-box[0]-1),min(raw.height-1,y2-box[1]-1)),fill=(250,246,232))
        alpha = mask_crop(work, row['key']=='flint', [(x-box[0],y-box[1]) for x,y in row['backgroundSeeds']]).getchannel('A')
        ImageDraw.Draw(alpha).rectangle((0,row['groundCutY']-box[1],raw.width,raw.height), fill=0)
        image = raw.convert('RGBA')
        image.putalpha(alpha)
        image.save(ROOT / row['output'])
        # Reusing these assets must never quietly change an approved preparation.
        assert sha(ROOT / row['output']) == row['sha256'], row['id']
        actors.append(dict(id=row['id'], name=row['name'], src=row['output'],
                           width=row['width'], height=row['height'], sha256=row['sha256'],
                           source=row['source'], sourceSha256=row['sourceSha256'],
                           crop=box, anchor=row['anchor'], rgbPixelsUnchanged=True))
    assert len(actors) == len({a['id'] for a in actors}) == 42
    data = {**definition, 'actors': actors}
    write('assets/ending/roll-manifest.json', data)
    (ROOT/'game/dist/ending-roll-data.js').write_text('/* Generated by build_ending_roll.py from design/ending_roll.json and source masks. */\n(function(root){const data='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';if(typeof module!=="undefined")module.exports=data;else root.ArcEndingData=data;})(globalThis);\n')
    print('Reproduced 42 original-pixel ending cutouts and shared timeline data')

if __name__ == '__main__':
    build()
